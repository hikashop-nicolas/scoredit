#!/bin/sh
# Writes src/vendor/mp3-wasm.ts from a built encoder (scripts/build-mp3-wasm.sh calls it).
set -e
cd "$(dirname "$0")/.."
{
  echo "// Generated by scripts/build-mp3-wasm.sh from wasm/mp3: do not edit."
  echo "// MP3 encoder: rusty_mp3 1.0.5 (https://github.com/Remade-With-Rust/remade_ffmpeg_rs),"
  echo "// Apache License 2.0, compiled to WebAssembly (credited in README.md)."
  printf 'const wasm: string = "'
  base64 < "$1" | tr -d '\n'
  echo '";'
  echo 'export default wasm;'
} > src/vendor/mp3-wasm.ts
ls -l src/vendor/mp3-wasm.ts
