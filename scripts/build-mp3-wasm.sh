#!/bin/sh
# Builds wasm/mp3 (rusty_mp3, Apache-2.0) to src/vendor/mp3-wasm.ts. Needs a Rust toolchain
# with the wasm32-unknown-unknown target (rustup target add wasm32-unknown-unknown) and wasm-opt.
set -e
cd "$(dirname "$0")/../wasm/mp3"
cargo build --release --target wasm32-unknown-unknown
wasm-opt -O3 target/wasm32-unknown-unknown/release/scoredit_mp3.wasm -o target/mp3.wasm
cd ../..
{
  echo "// Generated by scripts/build-mp3-wasm.sh from wasm/mp3: do not edit."
  echo "// MP3 encoder: rusty_mp3 1.0.5 (https://github.com/Remade-With-Rust/remade_ffmpeg_rs),"
  echo "// Apache License 2.0, compiled to WebAssembly (credited in README.md, Sound)."
  printf 'export default "'
  base64 < wasm/mp3/target/mp3.wasm | tr -d '\n'
  echo '";'
} > src/vendor/mp3-wasm.ts
ls -l src/vendor/mp3-wasm.ts
